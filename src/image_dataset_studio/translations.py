LANG = "JP"


def set_language(language: str) -> None:
    global LANG
    if language not in {"JP", "EN"}:
        raise ValueError(language)
    LANG = language


def get_language() -> str:
    return LANG


def tr(entry: dict[str, str], **values) -> str:
    return entry[LANG].format(**values)
